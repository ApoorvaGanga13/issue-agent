import difflib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

TASKS_DIR = Path("evals/tasks")
TRACES_DIR = Path("evals/traces")
OUT_FILE = Path("evals/trace_findings.md")
DEFAULT_TASKS = ["13", "17", "22", "26", "27"]
PATTERN = re.compile(
    r"^(?:(?P<tag>[a-z]+)_)?(?P<ver>v\d+)_(?:run(?P<run>\d+)_)?(?P<task>\d\d_.+)\.json$"
)


def replay(task_dir, trace, tmp):
    """Rebuild the repo as the agent left it, by re-applying its successful edits."""
    repo = tmp / "repo"
    shutil.copytree(task_dir / "repo", repo)
    for e in trace:
        if e["type"] == "tool" and e["tool"] == "edit_file" and e["output"].startswith("Edit applied"):
            p = repo / e["args"]["path"]
            text = p.read_text()
            if text.count(e["args"]["old"]) == 1:
                p.write_text(text.replace(e["args"]["old"], e["args"]["new"]))
    return repo


def source_diff(original, final):
    out = []
    for p in sorted(final.rglob("*.py")):
        if p.name.startswith("test_") or "__pycache__" in p.parts:
            continue
        rel = p.relative_to(final)
        old = (original / rel).read_text() if (original / rel).exists() else ""
        out.extend(difflib.unified_diff(
            old.splitlines(keepends=True), p.read_text().splitlines(keepends=True),
            f"a/{rel}", f"b/{rel}",
        ))
    return "".join(out)


def run_all_tests(repo, hidden_dir):
    for f in hidden_dir.glob("test_*.py"):
        shutil.copy(f, repo / f.name)
    r = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"],
        cwd=repo, capture_output=True, text=True, timeout=120,
    )
    failed = re.findall(r"^(?:FAILED|ERROR) \S+?::(\S+)", r.stdout, re.M)
    return r.returncode, failed


def main():
    wanted = sys.argv[1:] or DEFAULT_TASKS
    entries = defaultdict(list)
    for f in sorted(TRACES_DIR.glob("*.json")):
        m = PATTERN.match(f.name)
        if not m or not any(m["task"].startswith(w) for w in wanted):
            continue
        entries[m["task"]].append((m["ver"], m["tag"] or "early", int(m["run"] or 1), f))

    lines = [
        "# Trace findings",
        "",
        "Generated by `evals/why_failed.py`. For each saved run, the edits the agent made are",
        "replayed onto the original task repo, then the visible and hidden tests are run.",
        "",
    ]
    for task in sorted(entries):
        task_dir = TASKS_DIR / task
        hidden_dir = task_dir / "hidden"
        if not hidden_dir.exists():
            continue
        print(f"\n{task}")
        lines += [f"## {task}", ""]
        for ver, tag, run, f in sorted(entries[task]):
            trace = json.loads(f.read_text())
            tmp = Path(tempfile.mkdtemp())
            try:
                repo = replay(task_dir, trace, tmp)
                diff = source_diff(task_dir / "repo", repo)
                code, failed = run_all_tests(repo, hidden_dir)
            finally:
                shutil.rmtree(tmp, ignore_errors=True)
            status = "passes all tests" if code == 0 else "FAILS: " + (", ".join(failed) or "see test output")
            label = f"{ver} / {tag} / run {run}"
            print(f"  {label:<26} {status}")
            lines += [f"**{label}**: {status}", "", "```diff", diff or "(no source changes)", "```", ""]

    OUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {OUT_FILE}")


if __name__ == "__main__":
    main()
