import json
import re
from collections import defaultdict
from pathlib import Path

RESULTS = Path("evals/results")
README = Path("README.md")
PATTERN = re.compile(r"^(?P<tag>.+)_(?P<ver>v\d+)_run(?P<run>\d+)\.json$")
LABELS = {
    "heldout": "Held-out tasks 18-22",
    "extra": "Held-out tasks 23-27",
    "hard": "Fresh multi-file tasks 28-34",
    "docker": "Tasks 18-22 in the Docker sandbox",
}
ORDER = list(LABELS)

groups = defaultdict(list)  # (tag, prompt) -> [(run number, results)]
for f in sorted(RESULTS.glob("*_run*.json")):
    m = PATTERN.match(f.name)
    if m:
        groups[(m["tag"], m["ver"])].append((int(m["run"]), json.loads(f.read_text())))
if not groups:
    raise SystemExit("No result files found in evals/results, so nothing was changed.")


def sort_key(item):
    tag, ver = item[0]
    return (ORDER.index(tag) if tag in ORDER else len(ORDER), tag, ver)


table = [
    "| Task set | Prompt | Solved per run | Total | Rate |",
    "|---|---|---|---|---|",
]
all_runs = 0
edited = []  # (prompt, task)
for (tag, ver), runs in sorted(groups.items(), key=sort_key):
    runs.sort(key=lambda x: x[0])
    per_run = []
    solved = total = 0
    for _, results in runs:
        s = sum(1 for r in results if r["solved"])
        per_run.append(f"{s}/{len(results)}")
        solved += s
        total += len(results)
        all_runs += len(results)
        for r in results:
            if r.get("tampered"):
                edited.append((ver, r["task"]))
    label = LABELS.get(tag, tag)
    table.append(f"| {label} | {ver} | {', '.join(per_run)} | {solved}/{total} | {round(100 * solved / total)}% |")

if not edited:
    tamper = f"Across all {all_runs} saved task-runs, the agent never edited the visible test files."
else:
    by_ver = defaultdict(int)
    for ver, _ in edited:
        by_ver[ver] += 1
    detail = ", ".join(f"{n} with prompt {v}" for v, n in sorted(by_ver.items()))
    tasks = ", ".join(sorted({t for _, t in edited}))
    tamper = (
        "The agent is told never to edit the visible tests, but it sometimes does. "
        f"Across all {all_runs} saved task-runs, {len(edited)} were marked failed for editing them "
        f"({detail}; tasks: {tasks}). Making the test files read-only for the agent is on the roadmap."
    )

parts = [
    "Generated by `evals/finalize_readme.py` from the saved result files in `evals/results/`. "
    "A run counts as solved only if the hidden tests pass and the agent did not edit the visible tests.",
    "\n".join(table),
    tamper,
]
if ("hard", "v3") in groups:
    parts.append(
        "On the fresh multi-file tasks, the misses I traced had the same cause: the agent fixed the symptom "
        "that the visible tests pointed at, but did not check the code against the README spec. In task 34, "
        "the hidden test for \"no path returns -1\" failed in both traced v3 runs. In task 28, the senior ticket "
        "price (900 in the README, 90 in the code) was missed in one of the two traced v3 runs."
    )
content = "\n\n".join(parts)

text = README.read_text(encoding="utf-8-sig")
body = "<!-- generated:start -->\n" + content + "\n<!-- generated:end -->"
if "<!-- generated:start -->" in text:
    text = re.sub(r"<!-- generated:start -->.*?<!-- generated:end -->", lambda m: body, text, flags=re.S)
elif "## Limitations" in text:
    text = text.replace("## Limitations", "## Latest benchmark runs\n\n" + body + "\n\n## Limitations", 1)
else:
    raise SystemExit("Could not find '## Limitations' in README.md, so nothing was changed.")

anchor = "- Test with a second model"
if anchor in text and "read-only for the agent" not in text:
    text = text.replace(
        anchor,
        anchor
        + "\n- Make the test files read-only for the agent and measure the effect"
        + "\n- Add a prompt that checks the code against the written spec, then test it on fresh tasks",
        1,
    )
if "## License" not in text:
    text = text.rstrip("\n") + "\n\n## License\n\nMIT. See the LICENSE file.\n"

README.write_text(text, encoding="utf-8")
print("README updated.\n")
print("\n".join(table))
print(f"\nVisible-test edits: {len(edited)} of {all_runs} task-runs")
